import asyncio
import edge_tts

SCRIPT_TEXT = """
各位評審大家好，我們是 Temple AI OS 團隊。
全台灣有一萬兩千多座宮廟，每年承載無數信眾的心靈寄託。
然而在數位時代，年輕信眾常因不熟悉參拜規矩而退怯；廟方志工更每天陷在繁重的紙本報名、重複客服與電話通知中。
我們問：能不能把整座宮廟的服務與文化，完整收進大家最熟悉的 LINE 裡？

這就是 Temple AI OS。信眾不用下載任何 App，掃碼就能加入 LINE 官方帳號。
透過精心規劃的 6 格圖文選單，信眾能隨時問、隨時查、隨時報名。
當我們點選「詢問參拜方式」——後端以在地知識庫快速分析，精準提供萬春宮媽祖參拜動線與交通資訊。
更重要的是，我們的 AI 嚴格恪守安全防護守則，絕不扮演神明宣稱神諭，每則回覆皆附有正式公告免責提醒。
同時，系統會智慧推薦近期活動，以精美的輪播卡片呈現在信眾眼前。

點擊卡片，直接在 LINE 內部滑出輕量報名表單。
透過 LINE Login 自動驗證身分，零阻力送出報名。
底層採用資料庫行鎖機制，徹底防止活動超額並發。
報名完成後，信眾隨時能在選單中查詢自己的報名序號與審核狀態，完全告別打電話確認的傳統困擾。

接著來看廟方端。管理者登入後台儀表板，剛才信眾送出的報名即時同步顯示！
管理者可以一鍵審核、匯出名單，並看見信眾最常詢問的 AI 熱門話題與知識缺口。
系統更提供嚴格的權限控管與稽核日誌，讓宮廟幹事在辦公室就能輕鬆掌舵大型活動。

除了實用服務，我們更結合文化抽籤、線上擲筊與 LINE 原生文創貼圖，讓信仰年輕化、生活化。
Temple AI OS 已完成公開 Demo 部署，並以萬春宮公開資料建立示範場景。
我們希望能以此為起點，推廣至全台千座宮廟，用科技賦能信仰，讓百年文化代代相傳。謝謝各位評審！
"""

async def main():
    comm = edge_tts.Communicate(SCRIPT_TEXT.strip(), "zh-TW-YunJheNeural", rate="+3%")
    async for chunk in comm.stream():
        if chunk["type"] == "SentenceBoundary":
            start_s = chunk["offset"] / 10_000_000
            dur_s = chunk["duration"] / 10_000_000
            print(f"[{start_s:6.2f}s - {start_s+dur_s:6.2f}s] {chunk['text']}")

if __name__ == "__main__":
    asyncio.run(main())
